// writeBackendTF writes a minimal backend.tf to the directory for DiscoverBackendConfig.
func writeBackendTF(t *testing.T, dir string) {
	t.Helper()
	err := os.WriteFile(filepath.Join(dir, "backend.tf"), []byte(`
terraform {
  backend "azurerm" {
    storage_account_name = "testacct"
    container_name       = "testcontainer"
  }
}
`), 0o644)
	if err != nil {
		t.Fatal(err)
	}
}
