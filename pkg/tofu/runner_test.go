package tofu

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/terraprovider/statebridge/pkg/generator"
)

func writeMigrationFile(t *testing.T, dir, filename, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, filename), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestScanMigrationTargets_SingleFile(t *testing.T) {
	dir := t.TempDir()

	meta := &generator.MigrationMetadata{
		Resources: []string{"aws_instance.web", "aws_s3_bucket.data"},
	}
	content := "# Generated by statebridge - do not edit manually\n" +
		generator.RenderMetadataComment(meta) +
		"\nimport {\n  to = aws_instance.web\n  id = \"i-123\"\n}\n"

	writeMigrationFile(t, dir, "migration.001_move.a1b2c3d4.tf", content)

	addrs, err := ScanMigrationTargets(dir)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(addrs) != 2 {
		t.Fatalf("expected 2 addresses, got %d: %v", len(addrs), addrs)
	}
	if addrs[0] != "aws_instance.web" {
		t.Errorf("expected aws_instance.web first (sorted), got %q", addrs[0])
	}
	if addrs[1] != "aws_s3_bucket.data" {
		t.Errorf("expected aws_s3_bucket.data second, got %q", addrs[1])
	}
}

func TestScanMigrationTargets_MultipleFiles(t *testing.T) {
	dir := t.TempDir()

	meta1 := &generator.MigrationMetadata{
		Resources: []string{"aws_instance.web", "aws_s3_bucket.data"},
	}
	content1 := "# Generated\n" + generator.RenderMetadataComment(meta1) + "\n"
	writeMigrationFile(t, dir, "migration.001_move.aaaa0000.tf", content1)

	meta2 := &generator.MigrationMetadata{
		Resources: []string{"aws_s3_bucket.data", "aws_vpc.main"},
	}
	content2 := "# Generated\n" + generator.RenderMetadataComment(meta2) + "\n"
	writeMigrationFile(t, dir, "migration.002_rename.bbbb1111.tf", content2)

	addrs, err := ScanMigrationTargets(dir)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	// Deduplicated and sorted: aws_instance.web, aws_s3_bucket.data, aws_vpc.main
	if len(addrs) != 3 {
		t.Fatalf("expected 3 deduplicated addresses, got %d: %v", len(addrs), addrs)
	}
	expected := []string{"aws_instance.web", "aws_s3_bucket.data", "aws_vpc.main"}
	for i, exp := range expected {
		if addrs[i] != exp {
			t.Errorf("addrs[%d] = %q, want %q", i, addrs[i], exp)
		}
	}
}

