func TestScanMigrationTargets_NonMigrationFilesIgnored(t *testing.T) {
	dir := t.TempDir()

	// Non-migration .tf file should be ignored
	writeMigrationFile(t, dir, "main.tf", "resource \"aws_instance\" \"web\" {}")

	meta := &generator.MigrationMetadata{
		Resources: []string{"aws_vpc.main"},
	}
	content := "# Generated\n" + generator.RenderMetadataComment(meta) + "\n"
	writeMigrationFile(t, dir, "migration.001_net.cccc2222.tf", content)

	addrs, err := ScanMigrationTargets(dir)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(addrs) != 1 {
		t.Fatalf("expected 1 address, got %d: %v", len(addrs), addrs)
	}
	if addrs[0] != "aws_vpc.main" {
		t.Errorf("expected aws_vpc.main, got %q", addrs[0])
	}
}

func TestScanMigrationTargets_WithConditions(t *testing.T) {
	dir := t.TempDir()

	meta := &generator.MigrationMetadata{
		Conditions: &generator.MetadataCondition{
			ResourcesExist: []generator.MetadataResourceCheck{
				{Layer: ".", Addresses: []string{"aws_instance.web"}},
			},
		},
		Resources: []string{"aws_instance.web"},
	}
	content := "# Generated\n" + generator.RenderMetadataComment(meta) + "\n"
	writeMigrationFile(t, dir, "migration.001_move.dddd3333.tf", content)

	addrs, err := ScanMigrationTargets(dir)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(addrs) != 1 {
		t.Fatalf("expected 1 address, got %d", len(addrs))
	}
	if addrs[0] != "aws_instance.web" {
		t.Errorf("expected aws_instance.web, got %q", addrs[0])
	}
}
