func TestMetadataSourceLayer_Matches(t *testing.T) {
	tests := []struct {
		name             string
		descriptor       *MetadataSourceLayer
		account          string
		container        string
		key              string
		wantMatch        bool
		wantDeterminable bool
	}{
		{
			name:       "nil descriptor matches everything",
			descriptor: nil,
			account:    "a", container: "c", key: "k",
			wantMatch: true, wantDeterminable: true,
		},
		{
			name:       "full triple exact match",
			descriptor: &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c", Key: "k1"},
			account:    "a", container: "c", key: "k1",
			wantMatch: true, wantDeterminable: true,
		},
		{
			name:       "different key is determinable mismatch",
			descriptor: &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c", Key: "k1"},
			account:    "a", container: "c", key: "k2",
			wantMatch: false, wantDeterminable: true,
		},
		{
			name:       "keyed descriptor but caller has no key is indeterminate",
			descriptor: &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c", Key: "k1"},
			account:    "a", container: "c", key: "",
			wantMatch: false, wantDeterminable: false,
		},
		{
			name:       "empty descriptor fields act as wildcards",
			descriptor: &MetadataSourceLayer{Key: "k1"},
			account:    "any", container: "any", key: "k1",
			wantMatch: true, wantDeterminable: true,
		},
		{
			name:       "account mismatch",
			descriptor: &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c"},
			account:    "b", container: "c", key: "",
			wantMatch: false, wantDeterminable: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			match, determinable := tt.descriptor.Matches(tt.account, tt.container, tt.key)
			if match != tt.wantMatch {
				t.Errorf("match = %v, want %v", match, tt.wantMatch)
			}
			if determinable != tt.wantDeterminable {
				t.Errorf("determinable = %v, want %v", determinable, tt.wantDeterminable)
			}
		})
	}
}

func TestMetadataSourceLayer_OwnedByOther(t *testing.T) {
	tests := []struct {
		name       string
		descriptor *MetadataSourceLayer
		account    string
		container  string
		key        string
		want       bool
	}{
		{"nil is never owned by other", nil, "a", "c", "k", false},
		{"exact match not owned by other", &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c", Key: "k1"}, "a", "c", "k1", false},
		{"determinable mismatch is owned by other", &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c", Key: "k1"}, "a", "c", "k2", true},
		{"indeterminate is not owned by other", &MetadataSourceLayer{StorageAccountName: "a", ContainerName: "c", Key: "k1"}, "a", "c", "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := tt.descriptor.OwnedByOther(tt.account, tt.container, tt.key); got != tt.want {
				t.Errorf("OwnedByOther = %v, want %v", got, tt.want)
			}
		})
	}
}
