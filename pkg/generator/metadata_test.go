func TestRenderAndParseMetadataRoundTrip(t *testing.T) {
	meta := &MigrationMetadata{
		Conditions: &MetadataCondition{
			ResourcesExist: []MetadataResourceCheck{
				{Layer: ".", Addresses: []string{"azurerm_resource_group.example"}},
			},
			ResourcesNotExist: []MetadataResourceCheck{
				{Layer: ".", Addresses: []string{"azurerm_virtual_network.old"}},
			},
		},
		Resources: []string{"azurerm_resource_group.example", "azurerm_virtual_network.main"},
	}

	rendered := RenderMetadataComment(meta)
	if rendered == "" {
		t.Fatal("RenderMetadataComment returned empty string")
	}

	// Verify markers present
	if !strings.Contains(rendered, "statebridge:metadata:begin") {
		t.Error("missing begin marker")
	}
	if !strings.Contains(rendered, "statebridge:metadata:end") {
		t.Error("missing end marker")
	}

	parsed, err := ParseMetadataComment(rendered)
	if err != nil {
		t.Fatalf("ParseMetadataComment error: %v", err)
	}
	if parsed == nil {
		t.Fatal("ParseMetadataComment returned nil")
	}

	// Verify round-trip
	if len(parsed.Resources) != 2 {
		t.Errorf("expected 2 resources, got %d", len(parsed.Resources))
	}
	if parsed.Resources[0] != "azurerm_resource_group.example" {
		t.Errorf("resource[0] = %q", parsed.Resources[0])
	}
	if parsed.Conditions == nil {
		t.Fatal("conditions is nil after round-trip")
	}
	if len(parsed.Conditions.ResourcesExist) != 1 {
		t.Errorf("expected 1 resources_exist check, got %d", len(parsed.Conditions.ResourcesExist))
	}
	if parsed.Conditions.ResourcesExist[0].Layer != "." {
		t.Errorf("resources_exist layer = %q, want %q", parsed.Conditions.ResourcesExist[0].Layer, ".")
	}
	if len(parsed.Conditions.ResourcesNotExist) != 1 {
		t.Errorf("expected 1 resources_not_exist check, got %d", len(parsed.Conditions.ResourcesNotExist))
	}
}

