func TestRelativizeCondition(t *testing.T) {
	cond := &MetadataCondition{
		ResourcesExist: []MetadataResourceCheck{
			{Layer: "./layers/compute", Addresses: []string{"azurerm_vm.web"}},
			{Layer: "./layers/network", Addresses: []string{"azurerm_vnet.main"}},
		},
		ResourcesNotExist: []MetadataResourceCheck{
			{Layer: "./layers/compute", Addresses: []string{"azurerm_vm.old"}},
		},
	}

	result := RelativizeCondition(cond, "./layers/compute")

	if result == nil {
		t.Fatal("expected non-nil result")
	}

	// The compute layer should be relativized to "."
	if result.ResourcesExist[0].Layer != "." {
		t.Errorf("expected layer '.' for compute, got %q", result.ResourcesExist[0].Layer)
	}
	// The network layer should remain as-is
	if result.ResourcesExist[1].Layer != "./layers/network" {
		t.Errorf("expected layer './layers/network', got %q", result.ResourcesExist[1].Layer)
	}
	// resources_not_exist should also be relativized
	if result.ResourcesNotExist[0].Layer != "." {
		t.Errorf("expected layer '.' for compute not_exist, got %q", result.ResourcesNotExist[0].Layer)
	}

	// Verify original was not modified
	if cond.ResourcesExist[0].Layer != "./layers/compute" {
		t.Error("original condition was modified")
	}
}

