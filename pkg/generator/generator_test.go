func TestWriter_GroupedByLayer(t *testing.T) {
	w := NewWriter()
	w.AddBlock(&ImportBlock{To: "a", ID: "1", Layer: "./layers/app"})
	w.AddBlock(&RemovedBlock{From: "b", Layer: "./layers/compute"})
	w.AddBlock(&MovedBlock{From: "c", To: "d", Layer: "./layers/app"})

	grouped := w.GroupedByLayer()
	if len(grouped["./layers/app"]) != 2 {
		t.Errorf("expected 2 blocks for app layer, got %d", len(grouped["./layers/app"]))
	}
	if len(grouped["./layers/compute"]) != 1 {
		t.Errorf("expected 1 block for compute layer, got %d", len(grouped["./layers/compute"]))
	}
}

func TestWriter_RenderLayer(t *testing.T) {
	w := NewWriter()
	w.AddBlock(&MovedBlock{
		From:        "module.old_vpc",
		To:          "module.new_vpc",
		Layer:       "./layers/networking",
		Description: "Rename VPC module",
	})

	content := w.RenderLayer("./layers/networking")
	if !strings.Contains(content, "# Generated by tfmigrate") {
		t.Error("expected header comment in output")
	}
	if !strings.Contains(content, "module.old_vpc") {
		t.Error("expected moved block from address in output")
	}
	if !strings.Contains(content, "module.new_vpc") {
		t.Error("expected moved block to address in output")
	}
	if !strings.Contains(content, "# Rename VPC module") {
		t.Error("expected description comment in output")
	}
}

