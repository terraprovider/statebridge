func TestWriter_RenderAll_MultipleLayersAggregated(t *testing.T) {
	w := NewWriter()
	w.AddBlock(&RemovedBlock{From: "aws_instance.web", Layer: "./src"})
	w.AddBlock(&ImportBlock{To: "aws_instance.web", ID: "i-123", Layer: "./dst"})
	w.AddBlock(&RemovedBlock{From: "aws_instance.api", Layer: "./src"})

	all := w.RenderAll()

	srcContent := all["./src"]
	if strings.Count(srcContent, "removed {") != 2 {
		t.Errorf("expected 2 removed blocks in source layer, got content:\n%s", srcContent)
	}

	dstContent := all["./dst"]
	if strings.Count(dstContent, "import {") != 1 {
		t.Errorf("expected 1 import block in dest layer, got content:\n%s", dstContent)
	}
}

func TestWriter_WriteAll(t *testing.T) {
	dir := t.TempDir()
	layerDir := filepath.Join(dir, "layers", "app")
	if err := os.MkdirAll(layerDir, 0o755); err != nil {
		t.Fatal(err)
	}

	w := NewWriter()
	w.AddBlock(&ImportBlock{
		To:    "aws_instance.web",
		ID:    "i-123",
		Layer: layerDir,
	})

	files, err := w.WriteAll()
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("expected 1 file, got %d", len(files))
	}

	content, err := os.ReadFile(files[0])
	if err != nil {
		t.Fatalf("reading output file: %v", err)
	}

	if !strings.Contains(string(content), "import {") {
		t.Error("expected import block in output file")
	}
	if !strings.Contains(string(content), `id = "i-123"`) {
		t.Error("expected import ID in output file")
	}
}

func TestWriter_WriteAll_DryRun(t *testing.T) {
	w := NewWriter()
	w.DryRun = true
	w.AddBlock(&ImportBlock{
		To:    "aws_instance.web",
		ID:    "i-123",
		Layer: "/nonexistent/layer",
	})

	files, err := w.WriteAll()
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("expected 1 file path, got %d", len(files))
	}

	// File should not actually exist
	if _, err := os.Stat(files[0]); !os.IsNotExist(err) {
		t.Error("expected file to not exist in dry-run mode")
	}
}

